        <h2>5. Your Rights Under the General Data Protection Regulation (GDPR)</h2>
        <p>At Loot Raiders, we recognize and respect your rights under the GDPR and related privacy laws.</p>
        <p>As a User of our platform, you retain full control over your personal data.</p>
        <p>You have the following rights:</p>

        <h3>Right of Access</h3>
        <p>You may request confirmation of whether Loot Raiders is processing your personal data.</p>
        <p>If so, you are entitled to access the data and receive detailed information about its processing.</p>

        <h3>Right to Rectification</h3>
        <p>If any of your personal data is inaccurate or incomplete, you have the right to request correction or
            updates.</p>

        <h3>Right to Erasure ("Right to be Forgotten")</h3>
        <p>You may request the deletion of your personal data when:</p>
        <ul>
            <li>It is no longer necessary for the purposes it was collected for, or</li>
            <li>The processing is based on your consent and you withdraw that consent.</li>
        </ul>

        <h3>Right to Restriction of Processing</h3>
        <p>You can request that Loot Raiders limits the processing of your data under certain conditions, such as:</p>
        <ul>
            <li>Contesting the accuracy of the data</li>
            <li>Objecting to its processing</li>
        </ul>

        <h3>Right to Data Portability</h3>
        <p>You have the right to request a copy of your personal data in a structured, commonly used, and
            machine-readable format.</p>
        <p>You may also request its direct transfer to another data controller, where technically feasible.</p>

        <h3>Right to Object</h3>
        <p>You may object at any time to:</p>
        <ul>
            <li>The processing of your personal data based on our legitimate interests</li>
            <li>The use of your data for direct marketing purposes</li>
        </ul>

        <h3>Right to Withdraw Consent</h3>
        <p>If processing is based on your consent, you may withdraw it at any time.</p>
        <p>Withdrawal does not affect the lawfulness of prior processing activities based on consent.</p>

        <h3>Right to Lodge a Complaint</h3>
        <p>If you believe your rights have been infringed, you have the right to lodge a complaint with a supervisory
            authority.</p>
        <p>In Costa Rica, you may contact the Agencia de Protección de Datos de los Habitantes (PRODHAB) or your local
            supervisory body.</p>

        <h3>Exercising Your Rights</h3>
        <p>To exercise any of the rights outlined above, please contact us:</p>
